    lines.append('        def dfs(node):')
    lines.append('            if node:')
    lines.append('                dfs(node.left)')
    lines.append('                result.append(node.val)')
    lines.append('                dfs(node.right)')
    lines.append('        dfs(self.root)')
    lines.append('        return result')
    lines.append('    def preorder(self) -> List[Any]:')
    lines.append('        result = []')
    lines.append('        def dfs(node):')
    lines.append('            if node:')
    lines.append('                result.append(node.val)')
    lines.append('                dfs(node.left)')
    lines.append('                dfs(node.right)')
    lines.append('        dfs(self.root)')
    lines.append('        return result')
    lines.append('    def postorder(self) -> List[Any]:')
    lines.append('        result = []')
    lines.append('        def dfs(node):')
    lines.append('            if node:')
    lines.append('                dfs(node.left)')
    lines.append('                dfs(node.right)')
    lines.append('                result.append(node.val)')
    lines.append('        dfs(self.root)')
    lines.append('        return result')
    lines.append('    def level_order(self) -> List[List[Any]]:')
    lines.append('        if not self.root:')
    lines.append('            return []')
    lines.append('        result = []')
    lines.append('        queue = deque([self.root])')
    lines.append('        while queue:')
    lines.append('            level = []')
    lines.append('            for _ in range(len(queue)):')
    lines.append('                node = queue.popleft()')
    lines.append('                level.append(node.val)')
    lines.append('                if node.left:')
    lines.append('                    queue.append(node.left)')
    lines.append('                if node.right:')
    lines.append('                    queue.append(node.right)')
    lines.append('            result.append(level)')
    lines.append('        return result')
    lines.append('    def height(self) -> int:')
    lines.append('        def dfs(node):')
    lines.append('            if not node:')
    lines.append('                return 0')
    lines.append('            return 1 + max(dfs(node.left), dfs(node.right))')
    lines.append('        return dfs(self.root)')
    lines.append('    def search(self, val: Any) -> bool:')
    lines.append('        def dfs(node):')
    lines.append('            if not node:')
    lines.append('                return False')
    lines.append('            if node.val == val:')
    lines.append('                return True')
    lines.append('            return dfs(node.left) or dfs(node.right)')
    lines.append('        return dfs(self.root)')
    lines.append('')

    # Trie
    lines.append('class TrieNode_%04d:' % start)
    lines.append('    """Trie node %d"""' % start)
    lines.append('    def __init__(self):')
