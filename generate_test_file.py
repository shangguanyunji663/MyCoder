    # LinkedList
    lines.append('class LinkedList_%04d:' % start)
    lines.append('    """Linked list %d"""' % start)
    lines.append('    def __init__(self):')
    lines.append('        self.head = None')
    lines.append('        self._size = 0')
    lines.append('    def append(self, val: Any) -> None:')
    lines.append('        node = ListNode_%04d(val)' % start)
    lines.append('        if not self.head:')
    lines.append('            self.head = node')
    lines.append('        else:')
    lines.append('            cur = self.head')
    lines.append('            while cur.next:')
    lines.append('                cur = cur.next')
    lines.append('            cur.next = node')
    lines.append('        self._size += 1')
    lines.append('    def prepend(self, val: Any) -> None:')
    lines.append('        node = ListNode_%04d(val, self.head)' % start)
    lines.append('        self.head = node')
    lines.append('        self._size += 1')
    lines.append('    def delete(self, val: Any) -> bool:')
    lines.append('        if not self.head:')
    lines.append('            return False')
    lines.append('        if self.head.val == val:')
    lines.append('            self.head = self.head.next')
    lines.append('            self._size -= 1')
    lines.append('            return True')
    lines.append('        cur = self.head')
    lines.append('        while cur.next:')
    lines.append('            if cur.next.val == val:')
    lines.append('                cur.next = cur.next.next')
    lines.append('                self._size -= 1')
    lines.append('                return True')
    lines.append('            cur = cur.next')
    lines.append('        return False')
    lines.append('    def find(self, val: Any):')
    lines.append('        cur = self.head')
    lines.append('        while cur:')
    lines.append('            if cur.val == val:')
